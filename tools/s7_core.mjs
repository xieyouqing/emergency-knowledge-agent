/**
 * S7 动作动词表的唯一实现。
 *
 * 为什么要单独一份：
 *   `check_s7_suite.mjs`（离线校验器）和 `llm_proxy.mjs`（P5 生成链路）
 *   都必须用同一张表。两处各写一份，改了一处另一处不动，
 *   就会出现「校验器说 B、生成链路说安全」的分叉。
 *
 * 表的内容与 2026-11-20 的 check_s7 完全一致；只收「对世界产生改变的动词」。
 * 刻意不收：防、玩、有、是、给、记住、注意、建议、最好。
 */
export const ACT_VERBS = [
  '安装', '装', '关掉', '关闭', '关', '打开', '开窗', '开', '放', '换', '更换', '检查', '查',
  '冲', '浸泡', '泡', '包住', '包', '送到', '送医', '送', '拨打', '打电话', '打', '拨', '按',
  '切', '捂', '爬', '走', '跑', '拔', '试跳', '跳', '扶', '擦', '洗', '煮', '盖', '躲', '蹲',
  '趴', '喊', '叫', '拿', '抓', '咬', '吞', '喝', '穿', '脱', '剪', '固定', '清理', '买',
  '备', '存放', '设置', '联系', '报修', '就医', '服用', '等', '嚼', '咽', '通', '试',
];

export const VERB_RE = new RegExp(ACT_VERBS.slice().sort((a, b) => b.length - a.length).join('|'));

export function hasActionVerb(text) {
  return VERB_RE.test(String(text || ''));
}
